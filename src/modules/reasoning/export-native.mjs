/** Render original graphics into reviewed native Canvas modules, never execute AS. */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "../../..");
const recovery = "/home/ignat/code/mightymatica-source-recovery/objects/Movies";
const families = [
  ["paradox", "Paradox box", "Paradox box-ru"],
  ["burninghouse", "Burninghouse", "Burninghouse-ru"],
  ["grandma", "Grandmaclimbes", "Grandmaclimbes-ru"],
  ["hunter", "Hunter", "Hunter-ru"],
  ["snail", "Snail-eng", "Snail"],
  ["staruhi", "Staruhi-eng", "Staruhi"],
  ["tram", "Tram", "Tram-ru"],
  ["turtles", "Turtles", "Turtles-ru"],
  ["wine", "Wineandmilk", "Wineandmilk-ru"],
  ["bacteria", "Bacteria", "Bacteria-ru"],
  ["hand", "Hand1000", "Hand1000-ru"],
];
const run = (script, args) => {
  const result = spawnSync(process.execPath, [resolve(root, script), ...args], { stdio: "inherit" });
  if (result.status !== 0) throw new Error(`${script} failed.`);
};
const data = {};
for (const [key, english, russian] of families) {
  data[key] = {};
  for (const [locale, source] of [["en", english], ["ru", russian]]) {
    const metadata = JSON.parse(readFileSync(`${recovery}/${source}/metadata.json`, "utf8"));
    const directory = resolve(root, `src/modules/reasoning/source-export/${key}-${locale}`);
    const module = `reasoning/native/${key}-${locale}.mjs`;
    const output = resolve(root, "public/media", module);
    if (!process.argv.includes("--reuse-existing")) {
      run("scripts/export-original-frames.mjs", ["--source", `${recovery}/${source}/original/${source}.swf`,
        "--frames", `1-${metadata.frame_count}`, "--output", directory, "--format", "canvas"]);
      run("scripts/convert-canvas-export.mjs", [directory, output]);
    }
    const syntax = spawnSync(process.execPath, ["--check", output], { stdio: "inherit" });
    if (syntax.status !== 0) throw new Error(`Invalid converted JS: ${source}`);
    data[key][locale] = { module, source: `Movies/${source}.swf`, frames: metadata.frame_count,
      fps: metadata.frame_rate, sha256: metadata.sha256 };
  }
}
writeFileSync(resolve(root, "src/modules/reasoning/native-timelines.json"), `${JSON.stringify(data, null, 2)}\n`);
// Reapply verified text caching after future artwork recovery (or reuse).
// The family optimizer also protects the existing banknote companions.
run("src/modules/reasoning/recover-text-bounds.mjs", []);
run("src/modules/reasoning/optimize-painters.mjs", ["--apply"]);
run("src/modules/reasoning/optimize-static-painters.mjs", ["--recover"]);
run("src/modules/reasoning/optimize-static-painters.mjs", ["--apply"]);
run("scripts/optimize-reviewed-nested-filters.mjs", ["--apply", "--family", "reasoning"]);
run("scripts/optimize-reviewed-nested-filters.mjs", ["--apply", "--family", "dissections"]);
run("src/modules/reasoning/optimize-tram.mjs", ["--apply"]);
const recoveredControls = spawnSync("python3", [resolve(root, "scripts/recover-reasoning-logic-controls.py")], { stdio: "inherit" });
if (recoveredControls.status !== 0) throw new Error("Source control recovery failed.");
run("scripts/reasoning-logic-playback-control.mjs", ["--apply", "reasoning"]);
// Only disposable files generated by this script, never source archives.
rmSync(resolve(root, "src/modules/reasoning/source-export"), { recursive: true, force: true });
if (process.argv.includes("--remove-samples")) {
  rmSync(resolve(root, "public/media/reasoning/illustrated"), { recursive: true, force: true });
  const retained = new Set(JSON.parse(readFileSync(resolve(root, "src/modules/reasoning/paradox-scenes.json"), "utf8"))
    .map(scene => `${scene.first}.webp`));
  const folder = resolve(root, "public/media/reasoning/paradox-box");
  for (const file of readdirSync(folder)) if (/^\d+\.webp$/.test(file) && !retained.has(file)) {
    rmSync(resolve(folder, file));
  }
}
