export function sourceTriangleOptions(title: string, index: number, locale: Locale): readonly string[] {
  const ru = locale === "ru";
  const options = title === "congruence" ? index === 0 ?
    (ru ? ["Равны стороны", "Равны диагонали", "Равны площади", "Любой из трёх ответов"] : ["Equal sides", "Equal diagonals", "Equal areas", "Any of these three"]) :
    (ru ? ["Равны радиусы", "Равны длины окружностей", "Равны площади", "Любой из трёх ответов"] : ["Equal radii", "Equal circumferences", "Equal areas", "Any of these three"]) :
    title === "altitudes" && index === 4 && ru ? ["Прямоугольный", "Равносторонний", "Равнобедренный", "Любой"] : answers[title]?.[index];
  if (!options) throw new Error("Missing source triangle question.");
  return options;
}
